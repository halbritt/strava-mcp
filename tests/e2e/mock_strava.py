    def set_token_state(
        self,
        *,
        access_token: str | None = None,
        refresh_token: str | None = None,
        scopes: list[str] | str | None = None,
        expires_at: int | None = None,
        expires_in: int | None = None,
        athlete_id: int = DEFAULT_ATHLETE_ID,
    ) -> TokenRecord:
        with self._lock:
            now = int(time.time())
            resolved_access = access_token or self._default_access_token
            existing = self._tokens_by_access.get(resolved_access)
            resolved_refresh = refresh_token or (
                existing.refresh_token if existing else DEFAULT_REFRESH_TOKEN
            )
            if scopes is not None:
                resolved_scopes = _parse_scopes(scopes)
            elif existing is not None:
                resolved_scopes = list(existing.scopes)
            else:
                resolved_scopes = list(DEFAULT_SCOPES)
            if expires_at is not None:
                resolved_exp = int(expires_at)
            elif expires_in is not None:
                resolved_exp = now + int(expires_in)
            elif existing is not None:
                resolved_exp = existing.expires_at
            else:
                resolved_exp = now + self._token_ttl_seconds
            if existing is not None and existing.refresh_token != resolved_refresh:
                self._tokens_by_refresh.pop(existing.refresh_token, None)
            self._invalidated_refresh_tokens.discard(resolved_refresh)
            record = TokenRecord(
                access_token=resolved_access,
                refresh_token=resolved_refresh,
                scopes=resolved_scopes,
                expires_at=resolved_exp,
                athlete_id=athlete_id,
                revoked=False,
            )
            self._tokens_by_access[resolved_access] = record
            self._tokens_by_refresh[resolved_refresh] = record
            self._default_access_token = resolved_access
            return copy.deepcopy(record)

