    def _compute_stats_locked(self) -> dict[str, Any]:
        now = int(time.time())
        cutoff_28d = now - 28 * 86400
        ytd_year = datetime.fromtimestamp(now, tz=UTC).year

        def _empty_total() -> dict[str, Any]:
            return {
                "count": 0,
                "distance": 0.0,
                "moving_time": 0,
                "elapsed_time": 0,
                "elevation_gain": 0.0,
                "achievement_count": 0,
            }

        def _add(bucket: dict[str, Any], act: dict[str, Any]) -> None:
            bucket["count"] += 1
            bucket["distance"] = round(bucket["distance"] + float(act["distance"]), 1)
            bucket["moving_time"] += int(act["moving_time"])
            bucket["elapsed_time"] += int(act["elapsed_time"])
            bucket["elevation_gain"] = round(
                bucket["elevation_gain"] + float(act["total_elevation_gain"]), 1
            )
            bucket["achievement_count"] += int(act.get("achievement_count", 0))

        buckets: dict[str, dict[str, Any]] = {
            "recent_ride_totals": _empty_total(),
            "recent_run_totals": _empty_total(),
            "recent_swim_totals": _empty_total(),
            "ytd_ride_totals": _empty_total(),
            "ytd_run_totals": _empty_total(),
            "ytd_swim_totals": _empty_total(),
            "all_ride_totals": _empty_total(),
            "all_run_totals": _empty_total(),
            "all_swim_totals": _empty_total(),
        }
        biggest_ride = 0.0
        biggest_climb = 0.0
        for act in self._dataset["activities"].values():
            if act["visibility"] != "everyone":
                continue
            sport_key = {"Ride": "ride", "Run": "run", "Swim": "swim"}.get(act["type"])
            if sport_key is None:
                continue
            _add(buckets[f"all_{sport_key}_totals"], act)
            start_epoch = int(act["_start_epoch"])
            if datetime.fromtimestamp(start_epoch, tz=UTC).year == ytd_year:
                _add(buckets[f"ytd_{sport_key}_totals"], act)
            if start_epoch >= cutoff_28d:
                _add(buckets[f"recent_{sport_key}_totals"], act)
            if sport_key == "ride":
                biggest_ride = max(biggest_ride, float(act["distance"]))
                biggest_climb = max(biggest_climb, float(act["total_elevation_gain"]))
        return {
            "biggest_ride_distance": biggest_ride,
            "biggest_climb_elevation_gain": biggest_climb,
            **buckets,
        }

    def _paginate(self, items: list[Any], query: dict[str, list[str]]) -> list[Any]:
        try:
            page = max(1, int((query.get("page") or ["1"])[0]))
            per_page = min(200, max(1, int((query.get("per_page") or ["30"])[0])))
        except ValueError:
            page, per_page = 1, 30
        start = (page - 1) * per_page
        return items[start : start + per_page]

    def _clean_activity_summary(self, act: dict[str, Any]) -> dict[str, Any]:
        return {k: v for k, v in act.items() if not k.startswith("_")}

