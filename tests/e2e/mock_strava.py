def _parse_scopes(raw: str | list[str] | tuple[str, ...] | None) -> list[str]:
    if raw is None:
        return []
    parts: list[str] = []
    if isinstance(raw, str):
        parts = _SCOPE_SPLIT_RE.split(raw.strip())
    else:
        for item in raw:
            parts.extend(_SCOPE_SPLIT_RE.split(str(item).strip()))
    out: list[str] = []
    for part in parts:
        cleaned = part.strip()
        if cleaned and cleaned not in out:
            out.append(cleaned)
    return out


def _has_scope(granted: list[str], required: str) -> bool:
    expanded = set(granted)
    if "activity:read_all" in expanded:
        expanded.add("activity:read")
    if required == "read+":
        return bool(
            expanded
            & {"read", "read_all", "profile:read_all", "activity:read", "activity:read_all"}
        )
    return required in expanded


def _iso_utc(epoch: int) -> str:
    return datetime.fromtimestamp(epoch, tz=UTC).strftime("%Y-%m-%dT%H:%M:%SZ")


def _local_iso(epoch: int) -> str:
    return datetime.fromtimestamp(epoch - 28800, tz=UTC).strftime("%Y-%m-%dT%H:%M:%SZ")


