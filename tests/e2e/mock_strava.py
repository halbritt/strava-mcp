    def _consume_fault_locked(self, path: str) -> _FaultRule | None:
        idx = 0
        while idx < len(self._fault_rules):
            rule = self._fault_rules[idx]
            if rule.times is not None and rule.times <= 0:
                self._fault_rules.pop(idx)
                continue
            if rule.path_pattern is not None and not re.search(rule.path_pattern, path):
                idx += 1
                continue
            if rule.times is not None:
                rule.times -= 1
                if rule.times <= 0:
                    self._fault_rules.pop(idx)
            return rule
        return None

    def _apply_fault(
        self,
        rule: _FaultRule,
        rl_headers: dict[str, str],
    ) -> tuple[int, dict[str, str], bytes]:
        extra = dict(rl_headers)
        if rule.headers:
            extra.update(rule.headers)
        if rule.fault_type == "rate_limit_429":
            return self._json_response(
                429,
                _fault_json("Rate Limit Exceeded", "Application", "rate limit", "exceeded"),
                extra_headers=extra,
            )
        if rule.fault_type == "cloudfront_403":
            extra["Content-Type"] = "text/html; charset=utf-8"
            html = rule.body if isinstance(rule.body, str) else _cloudfront_html()
            return 403, extra, html.encode("utf-8")
        if rule.fault_type == "subscription_402":
            return self._json_response(
                402,
                _fault_json("Payment Required", "Athlete", "subscription", "required"),
                extra_headers=extra,
            )
        if rule.fault_type == "subscription_403":
            return self._json_response(
                403,
                _fault_json("Subscription required", "Athlete", "subscription", "required"),
                extra_headers=extra,
            )
        status = rule.status_code or 500
        if isinstance(rule.body, str):
            extra.setdefault("Content-Type", "text/plain; charset=utf-8")
            return status, extra, rule.body.encode("utf-8")
        payload = (
            rule.body if rule.body is not None else _fault_json("Injected error", code="error")
        )
        return self._json_response(status, payload, extra_headers=extra)

    def _handle_http_request(
        self,
        *,
        method: str,
        raw_path: str,
        headers: dict[str, str],
        body: str,
    ) -> tuple[int, dict[str, str], bytes]:
        split = urlsplit(raw_path)
        path = split.path
        query = parse_qs(split.query, keep_blank_values=True)
        with self._lock:
            if path.startswith("/oauth/") or path.startswith("/api/v3/oauth/"):
                status, resp_headers, resp_bytes = self._handle_oauth_locked(
                    method=method,
                    path=path,
                    query=query,
                    headers=headers,
                    body=body,
                )
            elif path.startswith("/api/v3/"):
                status, resp_headers, resp_bytes = self._handle_api_locked(
                    method=method,
                    path=path,
                    query=query,
                    headers=headers,
                )
            else:
                status, resp_headers, resp_bytes = self._json_response(
                    404,
                    _fault_json("Not Found", code="not_found"),
                )
            self._requests.append(
                RecordedRequest(
                    timestamp=time.time(),
                    method=method.upper(),
                    path=path,
                    query=query,
                    headers=headers,
                    body=body,
                    status_code=status,
                )
            )
            return status, resp_headers, resp_bytes

    def _handle_oauth_locked(
        self,
        *,
        method: str,
        path: str,
        query: dict[str, list[str]],
        headers: dict[str, str],
        body: str,
    ) -> tuple[int, dict[str, str], bytes]:
        oauth_path = path[len("/api/v3") :] if path.startswith("/api/v3/oauth/") else path
        if oauth_path == "/oauth/authorize" and method == "GET":
            return self._handle_oauth_authorize_locked(query)
        if oauth_path == "/oauth/token" and method == "POST":
            return self._handle_oauth_token_locked(query, body)
        if oauth_path == "/oauth/revoke" and method == "POST":
            return self._handle_oauth_revoke_locked(headers, body)
        if oauth_path == "/oauth/deauthorize" and method == "POST":
            return self._handle_oauth_deauthorize_locked(headers, query, body)
        return self._json_response(404, _fault_json("Not Found", code="not_found"))

    def _handle_oauth_authorize_locked(
        self,
        query: dict[str, list[str]],
    ) -> tuple[int, dict[str, str], bytes]:
        client_id = (query.get("client_id") or [""])[0]
        redirect_uri = (query.get("redirect_uri") or [""])[0]
        response_type = (query.get("response_type") or [""])[0]
        state = (query.get("state") or [""])[0]
        req_scope = (query.get("scope") or [""])[0]
        try:
            parsed_redir = urlsplit(redirect_uri) if redirect_uri else None
        except ValueError:
            parsed_redir = None
        if (
            client_id != self._client_id
            or response_type != "code"
            or parsed_redir is None
            or parsed_redir.scheme not in ("http", "https")
            or parsed_redir.hostname not in ("127.0.0.1", "localhost")
        ):
            return self._json_response(
                400,
                _fault_json("Invalid OAuth authorize parameters", "Authorization", "redirect_uri"),
            )
        existing_qs = parse_qs(parsed_redir.query, keep_blank_values=True)
        flat_params: dict[str, str] = {k: v[0] for k, v in existing_qs.items() if v}
        if self._oauth_deny_access or not self._oauth_auto_approve:
            flat_params["error"] = "access_denied"
            if state:
                flat_params["state"] = state
        else:
            granted = (
                list(self._oauth_consent_scopes)
                if self._oauth_consent_scopes is not None
                else (_parse_scopes(req_scope) or ["read"])
            )
            code = secrets.token_urlsafe(16)
            self._auth_codes[code] = _AuthCodeRecord(
                code=code,
                scopes=granted,
                expires_at=time.time() + 600.0,
                used=False,
            )
            flat_params["code"] = code
            flat_params["scope"] = ",".join(granted)
            if state:
                flat_params["state"] = state
        location = urlunsplit(
            (
                parsed_redir.scheme,
                parsed_redir.netloc,
                parsed_redir.path,
                urlencode(flat_params),
                "",
            )
        )
        return 302, {"Location": location, "Content-Type": "text/plain; charset=utf-8"}, b""

    def _handle_oauth_token_locked(
        self,
        query: dict[str, list[str]],
        body: str,
    ) -> tuple[int, dict[str, str], bytes]:
        form = parse_qs(body, keep_blank_values=True)
        for key, vals in query.items():
            form.setdefault(key, vals)
        client_id = (form.get("client_id") or [""])[0]
        client_secret = (form.get("client_secret") or [""])[0]
        grant_type = (form.get("grant_type") or [""])[0]
        if not (
            secrets.compare_digest(client_id, self._client_id)
            and secrets.compare_digest(client_secret, self._client_secret)
        ):
            return self._json_response(
                401,
                _fault_json("Authorization Error", "Application", "client_secret", "invalid"),
            )
        now = int(time.time())
        if grant_type == "authorization_code":
            code = (form.get("code") or [""])[0]
            auth_rec = self._auth_codes.get(code)
            if auth_rec is None or auth_rec.used or auth_rec.expires_at < time.time():
                return self._json_response(
                    400,
                    _fault_json("Bad Request", "AuthorizationCode", "code", "invalid"),
                )
            auth_rec.used = True
            new_access = f"synthetic-access-{secrets.token_urlsafe(12)}"
            new_refresh = f"synthetic-refresh-{secrets.token_urlsafe(12)}"
            expires_in = self._token_ttl_seconds
            expires_at = now + expires_in
            rec = TokenRecord(
                access_token=new_access,
                refresh_token=new_refresh,
                scopes=list(auth_rec.scopes),
                expires_at=expires_at,
                athlete_id=self._athlete_id,
            )
            self._tokens_by_access[new_access] = rec
            self._tokens_by_refresh[new_refresh] = rec
            self._default_access_token = new_access
            return self._json_response(
                200,
                {
                    "token_type": "Bearer",
                    "expires_at": expires_at,
                    "expires_in": expires_in,
                    "refresh_token": new_refresh,
                    "access_token": new_access,
                    "athlete": copy.deepcopy(self._dataset["summary_athlete"]),
                    "scope": " ".join(rec.scopes),
                },
            )
        if grant_type == "refresh_token":
            refresh_tok = (form.get("refresh_token") or [""])[0]
            if not refresh_tok or refresh_tok in self._invalidated_refresh_tokens:
                return self._json_response(
                    400,
                    _fault_json("Bad Request", "RefreshToken", "refresh_token", "invalid"),
                )
            rec = self._tokens_by_refresh.get(refresh_tok)
            if rec is None or rec.revoked:
                return self._json_response(
                    400,
                    _fault_json("Bad Request", "RefreshToken", "refresh_token", "invalid"),
                )
            remaining = rec.expires_at - now
            if self._enforce_one_hour_window and remaining > 3600:
                resp_access = rec.access_token
                resp_exp_at = rec.expires_at
                resp_exp_in = max(0, remaining)
                if self._rotate_within_hour:
                    resp_refresh = f"synthetic-refresh-{secrets.token_urlsafe(12)}"
                    self._invalidated_refresh_tokens.add(refresh_tok)
                    self._tokens_by_refresh.pop(refresh_tok, None)
                    rec.refresh_token = resp_refresh
                    self._tokens_by_refresh[resp_refresh] = rec
                else:
                    resp_refresh = rec.refresh_token
            else:
                resp_access = f"synthetic-access-{secrets.token_urlsafe(12)}"
                resp_refresh = f"synthetic-refresh-{secrets.token_urlsafe(12)}"
                resp_exp_in = self._token_ttl_seconds
                resp_exp_at = now + resp_exp_in
                self._invalidated_refresh_tokens.add(refresh_tok)
                self._tokens_by_refresh.pop(refresh_tok, None)
                new_rec = TokenRecord(
                    access_token=resp_access,
                    refresh_token=resp_refresh,
                    scopes=list(rec.scopes),
                    expires_at=resp_exp_at,
                    athlete_id=rec.athlete_id,
                )
                self._tokens_by_access[resp_access] = new_rec
                self._tokens_by_refresh[resp_refresh] = new_rec
                self._default_access_token = resp_access
            payload: dict[str, Any] = {
                "token_type": "Bearer",
                "access_token": resp_access,
                "expires_at": resp_exp_at,
                "expires_in": resp_exp_in,
                "refresh_token": resp_refresh,
            }
            if self._include_scope_on_refresh:
                payload["scope"] = " ".join(rec.scopes)
            if self._include_athlete_on_refresh:
                payload["athlete"] = copy.deepcopy(self._dataset["summary_athlete"])
            return self._json_response(200, payload)
        return self._json_response(
            400,
            _fault_json("Bad Request", "OAuth", "grant_type", "unsupported"),
        )

    def _handle_oauth_revoke_locked(
        self,
        headers: dict[str, str],
        body: str,
    ) -> tuple[int, dict[str, str], bytes]:
        auth_header = ""
        for k, v in headers.items():
            if k.lower() == "authorization":
                auth_header = v
                break
        if not auth_header.startswith("Basic "):
            return self._json_response(
                401,
                _fault_json("Authorization Error", "Application", "authorization", "invalid"),
            )
        try:
            decoded = base64.b64decode(auth_header[6:].strip()).decode("utf-8")
            cid, csec = decoded.split(":", 1)
        except Exception:
            cid, csec = "", ""
        if not (
            secrets.compare_digest(cid, self._client_id)
            and secrets.compare_digest(csec, self._client_secret)
        ):
            return self._json_response(
                401,
                _fault_json("Authorization Error", "Application", "client_secret", "invalid"),
            )
        form = parse_qs(body, keep_blank_values=True)
        token = (form.get("token") or [""])[0].strip()
        if not token:
            return self._json_response(
                400,
                _fault_json("Missing token", "OAuth", "token", "missing"),
            )
        hint = (form.get("token_type_hint") or [""])[0].strip()
        if hint and hint not in ("access_token", "refresh_token"):
            return self._json_response(
                400,
                _fault_json("Invalid token_type_hint", "OAuth", "token_type_hint", "invalid"),
            )
        rec = self._tokens_by_access.get(token) or self._tokens_by_refresh.get(token)
        if rec is not None:
            rec.revoked = True
            self._invalidated_refresh_tokens.add(rec.refresh_token)
            self._tokens_by_refresh.pop(rec.refresh_token, None)
        return 200, {"Content-Type": "text/plain; charset=utf-8"}, b""

    def _handle_oauth_deauthorize_locked(
        self,
        headers: dict[str, str],
        query: dict[str, list[str]],
        body: str,
    ) -> tuple[int, dict[str, str], bytes]:
        form = parse_qs(body, keep_blank_values=True)
        token = (form.get("access_token") or query.get("access_token") or [""])[0].strip()
        if not token:
            for k, v in headers.items():
                if k.lower() == "authorization" and v.startswith("Bearer "):
                    token = v[7:].strip()
                    break
        if not token:
            return self._json_response(
                401,
                _fault_json("Authorization Error", "Athlete", "access_token", "invalid"),
            )
        rec = self._tokens_by_access.get(token)
        if rec is None or rec.revoked:
            return self._json_response(
                401,
                _fault_json("Authorization Error", "Athlete", "access_token", "invalid"),
            )
        rec.revoked = True
        self._invalidated_refresh_tokens.add(rec.refresh_token)
        self._tokens_by_refresh.pop(rec.refresh_token, None)
        return self._json_response(200, {"access_token": token})

    def _handle_api_locked(
        self,
        *,
        method: str,
        path: str,
        query: dict[str, list[str]],
        headers: dict[str, str],
    ) -> tuple[int, dict[str, str], bytes]:
        if self._require_user_agent:
            ua = ""
            for k, v in headers.items():
                if k.lower() == "user-agent":
                    ua = v.strip()
                    break
            if not ua or ua.lower().startswith("python-urllib"):
                return (
                    403,
                    {"Content-Type": "text/html; charset=utf-8"},
                    _cloudfront_html().encode(),
                )
        self._overall_usage_15m += 1
        self._overall_usage_day += 1
        self._read_usage_15m += 1
        self._read_usage_day += 1
        rl = self._rate_limit_headers_locked()
        fault = self._consume_fault_locked(path)
        if fault is not None:
            return self._apply_fault(fault, rl)
        if (
            self._overall_usage_15m > self._overall_limit_15m
            or self._overall_usage_day > self._overall_limit_day
            or self._read_usage_15m > self._read_limit_15m
            or self._read_usage_day > self._read_limit_day
        ):
            return self._json_response(
                429,
                _fault_json("Rate Limit Exceeded", "Application", "rate limit", "exceeded"),
                extra_headers=rl,
            )
        token_val = ""
        for k, v in headers.items():
            if k.lower() == "authorization" and v.startswith("Bearer "):
                token_val = v[7:].strip()
                break
        rec = self._tokens_by_access.get(token_val)
        if rec is None or rec.revoked or rec.expires_at <= int(time.time()):
            return self._json_response(
                401,
                _fault_json("Authorization Error", "Athlete", "access_token", "invalid"),
                extra_headers=rl,
            )
        if method != "GET":
            return self._json_response(
                405, _fault_json("Method Not Allowed", code="method_not_allowed"), extra_headers=rl
            )
        return self._dispatch_api_get_locked(path=path, query=query, rec=rec, rl=rl)

