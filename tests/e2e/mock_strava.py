class _MockHTTPServer(ThreadingHTTPServer):
    daemon_threads = True
    allow_reuse_address = True

    def __init__(self, server_address: tuple[str, int], mock_server: MockStravaServer) -> None:
        self.mock_server = mock_server
        super().__init__(server_address, _MockRequestHandler)


class _MockRequestHandler(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"

    def log_message(self, format: str, *args: Any) -> None:
        return

    def do_GET(self) -> None:
        self._dispatch("GET")

    def do_POST(self) -> None:
        self._dispatch("POST")

    def _dispatch(self, method: str) -> None:
        length = int(self.headers.get("Content-Length") or 0)
        body = self.rfile.read(length).decode("utf-8", errors="replace") if length > 0 else ""
        server: MockStravaServer = self.server.mock_server  # type: ignore[attr-defined]
        status, resp_headers, resp_bytes = server._handle_http_request(
            method=method,
            raw_path=self.path,
            headers={k: v for k, v in self.headers.items()},
            body=body,
        )
        self.send_response(status)
        for key, value in resp_headers.items():
            self.send_header(key, value)
        self.send_header("Content-Length", str(len(resp_bytes)))
        self.send_header("Connection", "close")
        self.end_headers()
        if resp_bytes:
            self.wfile.write(resp_bytes)


class MockStravaServer:
    """Thread-safe local mock Strava OAuth2 & API v3 HTTP server."""

    def __init__(self) -> None:
        self._lock = threading.Lock()
        self._httpd: _MockHTTPServer | None = None
        self._thread: threading.Thread | None = None
        self.reset()

    def start(self) -> MockStravaServer:
        with self._lock:
            if self._httpd is not None:
                return self
            httpd = _MockHTTPServer(("127.0.0.1", 0), self)
            thread = threading.Thread(
                target=httpd.serve_forever,
                kwargs={"poll_interval": 0.05},
                daemon=True,
                name="mock-strava-http",
            )
            self._httpd = httpd
            self._thread = thread
            thread.start()
            return self

    def stop(self) -> None:
        with self._lock:
            httpd = self._httpd
            thread = self._thread
            self._httpd = None
            self._thread = None
        if httpd is not None:
            httpd.shutdown()
            httpd.server_close()
        if thread is not None and thread.is_alive():
            thread.join(timeout=2.0)

    def close(self) -> None:
        self.stop()

    def __enter__(self) -> MockStravaServer:
        return self.start()

    def __exit__(self, *_: object) -> None:
        self.stop()

